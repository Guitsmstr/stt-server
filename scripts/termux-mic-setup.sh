#!/bin/sh
# termux-mic-setup — prepare real microphone capture for `stt` (Stage 4).
#
# Run INSIDE the Alpine chroot as root.  It touches only the Android/Termux
# side:
#   1. grants RECORD_AUDIO to com.termux and com.termux.api;
#   2. builds + installs the runas-ctx helper in the Termux prefix with the
#      Termux app SELinux label;
#   3. records the uid/context in var/bin/termux-mic.env for the capture
#      script.
#
# The helper is needed because this chroot runs as root/Magisk, while Android
# audio capture only works for the Termux app uid in its untrusted_app domain.
# The script is idempotent and safe to re-run.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
PREFIX=${TERMUX_PREFIX:-/data/data/com.termux/files/usr}
ANDROID_ROOT=/proc/1/root
ENVFILE="$ROOT/var/bin/termux-mic.env"
TMPSCRIPT="$ANDROID_ROOT/data/local/tmp/stt-mic-setup.$$.sh"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing command: $1"; }

[ "$(id -u)" = 0 ] || die "run this script as root inside the chroot"
[ -d "$ANDROID_ROOT$PREFIX" ] || die "Termux prefix not found at $ANDROID_ROOT$PREFIX"
need nsenter
need cc

say "== Termux microphone setup =="
TERMUX_UID=$(stat -c %u "$ANDROID_ROOT/data/data/com.termux" 2>/dev/null || true)
[ -n "$TERMUX_UID" ] || die "cannot determine the Termux uid"
say "termux uid: $TERMUX_UID"
say "prefix:     $PREFIX"

# -- 1. /dev/null sanity (a regular file here breaks zygote/app process start)
if [ ! -c "$ANDROID_ROOT/dev/null" ]; then
    say "warning: /dev/null is not a character device; restoring it"
    rm -f "$ANDROID_ROOT/dev/null"
    mknod "$ANDROID_ROOT/dev/null" c 1 3
    chmod 666 "$ANDROID_ROOT/dev/null"
    chown 0:0 "$ANDROID_ROOT/dev/null"
    nsenter -t 1 -m -p -- /system/bin/chcon u:object_r:null_device:s0 /dev/null 2>/dev/null || true
fi

# -- 2. permissions and appops (shell domain has access to pm/cmd)
cat > "$TMPSCRIPT" <<'EOS'
#!/system/bin/sh
pm grant com.termux android.permission.RECORD_AUDIO || true
pm grant com.termux.api android.permission.RECORD_AUDIO || true
cmd appops set com.termux RECORD_AUDIO allow || true
cmd appops set com.termux.api RECORD_AUDIO allow || true
echo "termux: $(cmd appops get com.termux RECORD_AUDIO | tail -1)"
echo "api:    $(cmd appops get com.termux.api RECORD_AUDIO | tail -1)"
EOS
chmod 755 "$TMPSCRIPT"
nsenter -t 1 -m -p -- /system/bin/runcon u:r:shell:s0 /system/bin/sh \
    "/data/local/tmp/$(basename "$TMPSCRIPT")"
rm -f "$TMPSCRIPT"

# -- 3. build and install runas-ctx with the Termux app file label
mkdir -p "$ROOT/var/bin" "$ANDROID_ROOT$PREFIX/bin"
say "building runas-ctx"
cc -static -O2 -o "$ROOT/var/bin/runas-ctx" "$ROOT/scripts/android_runas.c"
cp "$ROOT/var/bin/runas-ctx" "$ANDROID_ROOT$PREFIX/bin/runas-ctx"
chown "$TERMUX_UID:$TERMUX_UID" "$ANDROID_ROOT$PREFIX/bin/runas-ctx"
chmod 755 "$ANDROID_ROOT$PREFIX/bin/runas-ctx"

FILE_CTX=$(nsenter -t 1 -m -p -- /system/bin/sh -c "ls -Z $PREFIX/bin/bash" | awk '{print $1}')
[ -n "$FILE_CTX" ] || die "cannot read the SELinux label of $PREFIX/bin/bash"
nsenter -t 1 -m -p -- /system/bin/chcon "$FILE_CTX" "$PREFIX/bin/runas-ctx"

# The process domain is not derivable from the file label: app_data_file is
# the file type, while the running Termux process uses untrusted_app_27.  Read
# it from a live process owned by the Termux uid.
PROC_CTX=
for pid in $(pgrep -u "$TERMUX_UID" 2>/dev/null || ps -A -o pid= 2>/dev/null); do
    [ "$(awk '/^Uid:/{print $2}' "/proc/$pid/status" 2>/dev/null)" = "$TERMUX_UID" ] || continue
    ctx=$(tr -d ' \n\0' < "/proc/$pid/attr/current" 2>/dev/null || true)
    case "$ctx" in
        *untrusted_app*) PROC_CTX=$ctx; break ;;
    esac
done
[ -n "$PROC_CTX" ] || die "cannot find a running Termux process context (open Termux once and retry)"
say "selinux label: $FILE_CTX"
say "process ctx:   $PROC_CTX"

# -- 4. persist the uid/context for scripts/termux-capture.sh
cat > "$ENVFILE" <<EOF
# generated by scripts/termux-mic-setup.sh
TERMUX_UID=$TERMUX_UID
TERMUX_CTX=$PROC_CTX
TERMUX_PREFIX=$PREFIX
EOF
chmod 644 "$ENVFILE"
say "wrote $ENVFILE"

# -- 5. verify the helper can run a Termux binary in the app context
say "verifying helper"
OUT=$(nsenter -t 1 -m -p -- /system/bin/sh -c \
    "export PREFIX=$PREFIX HOME=/data/data/com.termux/files/home PATH=$PREFIX/bin:/system/bin TMPDIR=$PREFIX/tmp LD_LIBRARY_PATH=$PREFIX/lib; \
     exec $PREFIX/bin/runas-ctx $TERMUX_UID '$PROC_CTX' $PREFIX/bin/id")
printf '%s\n' "$OUT"
printf '%s\n' "$OUT" | grep -q "uid=$TERMUX_UID" || die "runas-ctx verification failed"
printf '%s\n' "$OUT" | grep -q "context=$PROC_CTX" || die "runas-ctx context verification failed"

say
say "OK: microphone permissions and helper ready."
say "Next: ./scripts/termux-capture.sh --check"
